/* PL-10 handoff: writes the neighborhood list and its ZIP table from js/data.js (the one source) into docs/v5/handoff/
   as JSON, CSV and an idempotent Postgres seed, ready to move into the production app when Kevin says so.
   Run: node scripts/v5/export-neighborhoods.mjs   (re-run after any change to NEIGHBORHOODS / SHARED_ZIP_HOME) */
import { mkdirSync, writeFileSync } from 'node:fs';
import { BOROUGHS, NEIGHBORHOODS, SHARED_ZIP_HOME, placeForZip } from '../../js/data.js';

const OUT = new URL('../../docs/v5/handoff/', import.meta.url);
mkdirSync(OUT, { recursive: true });

const boroughs = BOROUGHS.map((b, i) => {
  const first = NEIGHBORHOODS.find((n) => n.borough === b.id);
  return { id: b.id, name: b.name, city: placeForZip(first.zips[0]).city, state: 'NY', sort: i + 1 };
});
const neighborhoods = NEIGHBORHOODS.map((n) => ({
  id: n.id, name: n.name, borough: n.borough, sort: NEIGHBORHOODS.filter((x) => x.borough === n.borough).indexOf(n) + 1, zips: [...n.zips],
}));
const allZips = [...new Set(neighborhoods.flatMap((n) => n.zips))].sort();
const zips = allZips.map((zip) => {
  const ids = neighborhoods.filter((n) => n.zips.includes(zip)).map((n) => n.id);
  const home = SHARED_ZIP_HOME[zip] ?? ids[0];
  if (ids.length > 1 && !SHARED_ZIP_HOME[zip]) throw new Error(`ZIP ${zip} is shared by ${ids.join(', ')} but has no home in SHARED_ZIP_HOME`);
  const borough = neighborhoods.find((n) => n.id === home).borough;
  return { zip, home, neighborhoods: ids, borough };
});

/* JSON — the full table */
writeFileSync(new URL('neighborhoods.json', OUT), `${JSON.stringify({
  about: 'Taily service area: the neighborhoods a tailor picks for home visits and the ZIP codes each covers. A ZIP is in Taily’s area when any neighborhood lists it; a shared ZIP reads as its "home" neighborhood. Generated from js/data.js by scripts/v5/export-neighborhoods.mjs (PL-10).',
  counts: { boroughs: boroughs.length, neighborhoods: neighborhoods.length, zips: zips.length, sharedZips: zips.filter((z) => z.neighborhoods.length > 1).length },
  boroughs, neighborhoods, zips,
}, null, 2)}\n`);

/* CSV — one row per neighborhood × ZIP, for a spreadsheet or an admin import */
const csv = [['borough', 'neighborhood_id', 'neighborhood', 'zip', 'shared_with', 'zip_reads_as']];
for (const n of neighborhoods) {
  for (const z of n.zips) {
    const row = zips.find((x) => x.zip === z);
    const others = row.neighborhoods.filter((id) => id !== n.id).map((id) => neighborhoods.find((x) => x.id === id).name);
    csv.push([boroughs.find((b) => b.id === n.borough).name, n.id, n.name, z, others.join('; '), neighborhoods.find((x) => x.id === row.home).name]);
  }
}
const cell = (v) => (/[",\n]/.test(v) ? `"${String(v).replace(/"/g, '""')}"` : String(v));
writeFileSync(new URL('neighborhoods.csv', OUT), `${csv.map((r) => r.map(cell).join(',')).join('\n')}\n`);

/* SQL — an idempotent Postgres (Supabase) seed: four small tables, upserts only, nothing deleted */
const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const sql = `-- Taily service area (PL-10). Generated by scripts/v5/export-neighborhoods.mjs from the prototype's js/data.js.
-- Idempotent: safe to run twice. It only creates and upserts; rows that left the list are NOT deleted (see the end).
-- Adapt table names to the production schema before running; nothing here has been run against production.

create table if not exists service_boroughs (
  id text primary key,
  name text not null,
  city text not null,
  state text not null default 'NY',
  sort int not null
);
create table if not exists service_neighborhoods (
  id text primary key,
  borough_id text not null references service_boroughs (id),
  name text not null,
  sort int not null
);
create table if not exists service_neighborhood_zips (
  neighborhood_id text not null references service_neighborhoods (id) on delete cascade,
  zip text not null check (zip ~ '^[0-9]{5}$'),
  primary key (neighborhood_id, zip)
);
-- every served ZIP once, with the neighborhood its address reads as (the "home" of a shared ZIP)
create table if not exists service_zips (
  zip text primary key check (zip ~ '^[0-9]{5}$'),
  home_neighborhood_id text not null references service_neighborhoods (id)
);

insert into service_boroughs (id, name, city, state, sort) values
${boroughs.map((b) => `  (${q(b.id)}, ${q(b.name)}, ${q(b.city)}, ${q(b.state)}, ${b.sort})`).join(',\n')}
on conflict (id) do update set name = excluded.name, city = excluded.city, state = excluded.state, sort = excluded.sort;

insert into service_neighborhoods (id, borough_id, name, sort) values
${neighborhoods.map((n) => `  (${q(n.id)}, ${q(n.borough)}, ${q(n.name)}, ${n.sort})`).join(',\n')}
on conflict (id) do update set borough_id = excluded.borough_id, name = excluded.name, sort = excluded.sort;

insert into service_neighborhood_zips (neighborhood_id, zip) values
${neighborhoods.flatMap((n) => n.zips.map((z) => `  (${q(n.id)}, ${q(z)})`)).join(',\n')}
on conflict do nothing;

insert into service_zips (zip, home_neighborhood_id) values
${zips.map((z) => `  (${q(z.zip)}, ${q(z.home)})`).join(',\n')}
on conflict (zip) do update set home_neighborhood_id = excluded.home_neighborhood_id;

-- Cleanup of rows that are no longer on the list is left to a person (it can orphan tailors' saved picks):
-- delete from service_neighborhood_zips where neighborhood_id not in (${neighborhoods.map((n) => q(n.id)).join(', ')});
-- delete from service_zips where zip not in (${allZips.map(q).join(', ')});
`;
writeFileSync(new URL('neighborhoods.sql', OUT), sql);

console.log(`wrote docs/v5/handoff/neighborhoods.{json,csv,sql}: ${boroughs.length} boroughs, ${neighborhoods.length} neighborhoods, ${zips.length} ZIPs (${zips.filter((z) => z.neighborhoods.length > 1).length} shared)`);
