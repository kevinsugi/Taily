/* One-off generator: docs/v5/SCREENS.md -> js/inventory.js (the machine copy).
   node scripts/v5/lib/gen-inventory.mjs   (rerun only if SCREENS.md changes; keep both in one commit) */
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../../..');
const md = readFileSync(resolve(ROOT, 'docs/v5/SCREENS.md'), 'utf8').split('\n');
const KIND = { '◆': 'frame', '·': 'state', O: 'overlay' };
const q = (v) => `'${String(v).replace(/'/g, "\\'")}'`;
const personaOf = (id) => (id.startsWith('c-') ? 'customer' : /^(t|to)-/.test(id) ? 'tailor' : 'system');

const screens = [];
for (const line of md) {
  const cells = line.split('|').map((c) => c.trim());
  if (cells.length < 6 || !/^`[a-z0-9-]+`$/.test(cells[1]) || !/^M\d$/.test(cells[2])) continue;
  const id = cells[1].slice(1, -1);
  const m = cells[2];
  const title = cells[3];
  const cell = cells[4];
  const states = [];
  let cur = m;
  const re = /(?:\b(M\d):\s*)?`([^`]+)`\s*(◆|O|·)?/g;
  let hit;
  while ((hit = re.exec(cell))) {
    if (hit[1]) cur = hit[1];
    states.push({ key: hit[2], m: cur, kind: KIND[hit[3]] ?? 'state' });
  }
  screens.push({ id, m, persona: personaOf(id), title, states });
}

/* system-wide patterns land on a host screen (SCREENS.md "System" second table) */
let inSys = false;
for (const line of md) {
  if (/^\| key \| M \| Host screen/.test(line)) { inSys = true; continue; }
  if (inSys && !line.startsWith('|')) inSys = false;
  if (!inSys) continue;
  const c = line.split('|').map((x) => x.trim());
  const key = c[1]?.replace(/`/g, '');
  if (!/^sys-/.test(key ?? '')) continue;
  const host = screens.find((s) => s.id === c[3].replace(/`/g, ''));
  if (host) host.states.push({ key, m: c[2], kind: /^O /.test(c[4]) ? 'overlay' : 'state' });
}

const out = `/* ============================================================
   Screen inventory — the machine copy of docs/v5/SCREENS.md (D-13).
   GENERATED by scripts/v5/lib/gen-inventory.mjs; edit SCREENS.md and
   regenerate, or edit both in one commit. \`npm run check\` fails when
   a state of a milestone listed in BUILT has no Test-flows entry.

   state.kind: 'frame' (sibling Figma frame) | 'state' (code-only) |
   'overlay' (sheet / modal opened by the entry's \`click\`).
   state.m overrides the screen's milestone.
   ============================================================ */

export const MILESTONES = [
  { id: 'M0', name: 'Foundation' },
  { id: 'M1', name: 'Customer booking' },
  { id: 'M2', name: 'Tailor onboarding + Shop' },
  { id: 'M3', name: 'Request loop' },
  { id: 'M4', name: 'Fitting to completion' },
  { id: 'M5', name: 'Messaging, accounts, earnings, system' },
  { id: 'M6', name: 'Final pass' },
];

/** Milestones whose screens are built (their state keys must all have FLOWS entries). */
export const BUILT = ['M0', 'M1', 'M2', 'M3'];

export const SCREENS = [
${screens.map((s) => `  { id: ${q(s.id)}, m: ${q(s.m)}, persona: ${q(s.persona)}, title: ${q(s.title)}, states: [
${s.states.map((st) => `    { key: ${q(st.key)}, m: ${q(st.m)}, kind: ${q(st.kind)} },`).join('\n')}
  ] },`).join('\n')}
];
`;
writeFileSync(resolve(ROOT, 'js/inventory.js'), out);
const total = screens.reduce((n, s) => n + s.states.length, 0);
console.log(`js/inventory.js: ${screens.length} screens, ${total} states`);
