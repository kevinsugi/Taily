/* Fetches the Phosphor icons Taily uses (MIT, @phosphor-icons/core@2.1.1) and writes js/phosphor.js.
   Usage: node scripts/v6/phosphor.mjs            (downloads any missing SVG, then regenerates js/phosphor.js)
          node scripts/v6/phosphor.mjs --refetch  (re-downloads everything)
   No dependencies. Regular weight everywhere; star-fill is the one Fill glyph (V6-D-07). */
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const VERSION = '2.1.1';
const CDN = `https://unpkg.com/@phosphor-icons/core@${VERSION}/assets`;
const REGULAR = [
  'house', 'calendar-check', 'chat-circle', 'user', 'storefront', 'money',
  'caret-left', 'caret-right', 'caret-down', 'dots-three', 'x', 'check', 'info', 'seal-check',
  'navigation-arrow', 'calendar-plus', 'lock-simple', 'clock', 'check-circle', 'warning', 'image', 'camera',
  'bell', 'wifi-slash', 'credit-card', 'plus', 'minus', 'map-pin', 'bag-simple', 'truck', 'pencil-simple',
  'coat-hanger', 'push-pin', 'star', 'arrow-clockwise',
];
const FILL = ['star-fill'];

const dir = resolve(ROOT, 'assets/phosphor');
mkdirSync(dir, { recursive: true });
const refetch = process.argv.includes('--refetch');
const jobs = [...REGULAR.map((n) => [n, `${CDN}/regular/${n}.svg`]), ...FILL.map((n) => [n, `${CDN}/fill/${n}.svg`])];
for (const [name, url] of jobs) {
  const file = resolve(dir, `${name}.svg`);
  if (existsSync(file) && !refetch) continue;
  execFileSync('curl', ['-sfL', url, '-o', file]);
}
const PH = {};
for (const [name] of jobs) {
  const svg = readFileSync(resolve(dir, `${name}.svg`), 'utf8').trim();
  const m = svg.match(/<svg[^>]*>([\s\S]*)<\/svg>/);
  if (!m) throw new Error(`${name}: not an svg`);
  PH[name] = m[1].trim();
}
const body = Object.entries(PH).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`).join('\n');
writeFileSync(resolve(ROOT, 'js/phosphor.js'),
`/* GENERATED by scripts/v6/phosphor.mjs from @phosphor-icons/core@${VERSION} (MIT, https://phosphoricons.com) — do not hand-edit.
   Inner SVG markup of each icon, 256 x 256 viewBox, fill="currentColor". Regular weight; star-fill is the one Fill glyph. */
export const PH = {
${body}
};
`);
console.log(`phosphor: ${jobs.length} icons -> js/phosphor.js`);
